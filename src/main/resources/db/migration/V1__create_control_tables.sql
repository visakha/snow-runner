-- Control tables for snow-runner (005 §2). One migration, valid on both
-- Snowflake and H2: TIMESTAMP is Snowflake's alias for TIMESTAMP_NTZ,
-- so the same statement runs on the test database and on production.
-- Production home is MDM_ETL_RUNNER.CONTROL (database name still needs
-- the user's confirmation); the schema is selected by the connection,
-- so these statements stay unqualified on purpose.

CREATE TABLE RUN (
  RUN_ID VARCHAR PRIMARY KEY,
  WORKFLOW_ID VARCHAR NOT NULL,
  SOURCE VARCHAR NOT NULL,
  STATUS VARCHAR NOT NULL,
  RUN_TS TIMESTAMP NOT NULL,
  TARGET_DATABASE VARCHAR NOT NULL,
  CATALOG_VERSION VARCHAR NOT NULL,
  APP_VERSION VARCHAR NOT NULL,
  TREE_VERSION VARCHAR NOT NULL,
  TRIGGERED_BY VARCHAR NOT NULL,
  IDEMPOTENCY_KEY VARCHAR,
  CURRENT_ATTEMPT_NO NUMBER NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  ENDED_AT TIMESTAMP,
  STEPS_SUCCEEDED NUMBER,
  STEPS_FAILED NUMBER,
  STEPS_SKIPPED NUMBER,
  ERROR_MESSAGE VARCHAR
);

CREATE TABLE RUN_STEP (
  RUN_ID VARCHAR NOT NULL,
  STEP_ID VARCHAR NOT NULL,
  ATTEMPT_NO NUMBER NOT NULL,
  STEP_POSITION NUMBER NOT NULL,
  PROCEDURE_NAME VARCHAR NOT NULL,
  STATUS VARCHAR NOT NULL,
  QUERY_ID VARCHAR,
  STARTED_AT TIMESTAMP,
  ENDED_AT TIMESTAMP,
  DURATION_MS NUMBER,
  ERROR_MESSAGE VARCHAR,
  SKIPPED_REASON VARCHAR,
  PRIMARY KEY (RUN_ID, STEP_ID, ATTEMPT_NO)
);

-- Current status per step: the highest-attempt row wins, because a
-- SUCCEEDED step gets no new row on a later attempt (005 §2).
CREATE VIEW RUN_STEP_CURRENT AS
SELECT RUN_ID, STEP_ID, ATTEMPT_NO, STEP_POSITION, PROCEDURE_NAME,
  STATUS, QUERY_ID, STARTED_AT, ENDED_AT, DURATION_MS,
  ERROR_MESSAGE, SKIPPED_REASON
FROM (
  SELECT RUN_STEP.*,
    ROW_NUMBER() OVER (
      PARTITION BY RUN_ID, STEP_ID ORDER BY ATTEMPT_NO DESC
    ) AS RN
  FROM RUN_STEP
)
WHERE RN = 1;
